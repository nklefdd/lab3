def import_faculty_content(apps, schema_editor):
    FacultyInfo = apps.get_model("faculty", "FacultyInfo")
    Department = apps.get_model("faculty", "Department")
    Teacher = apps.get_model("faculty", "Teacher")
    Program = apps.get_model("faculty", "Program")

    FacultyInfo.objects.create(
        name="Факультет гуманітарних наук",
        description=FACULTY_DESCRIPTION,
        contacts=FACULTY_CONTACTS,
    )

    departments = {}
    for name, head, teachers in DEPARTMENTS:
        department = Department.objects.create(name=name, head=head)
        departments[name] = department
        for teacher_name, position, degree in teachers:
            Teacher.objects.create(
                name=teacher_name,
                position=position,
                degree=degree,
                department=department,
            )

    for level in ("bachelor", "master"):
        for item in SPECIALTIES:
            name = item["name"]
            if level == "master":
                name = item.get("master_name", name)
            Program.objects.create(
                name=name,
                code=item["code"],
                level=level,
                description=item["description"] + LEVEL_TAIL[level],
                coordinator_name=item["coordinator"][0],
                coordinator_contact=item["coordinator"][1],
                department=departments[item["department"]],
                disciplines="\n".join(item[level]),
            )


